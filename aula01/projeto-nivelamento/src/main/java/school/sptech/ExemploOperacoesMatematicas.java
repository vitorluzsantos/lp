package school.sptech;

public class ExemploOperacoesMatematicas {
    public static void main(String[] args) {
        // +, -, /, %, **
        System.out.println("Soma: " + (10 + 10));
        System.out.println("Subtracao: " + (10 - 10));
        System.out.println("Multiplicação : " + (10 * 10));
        System.out.println("Divisão : " + (10 / 10));
        System.out.println("Módulo (resto da divisão) : " + (10 % 10));
        System.out.println("Potencialização : " + (Math.pow(10, 10)));
        System.out.println("Radiciação: " + (Math.sqrt(10)));
    }
}
